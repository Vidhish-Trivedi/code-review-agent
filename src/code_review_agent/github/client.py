import hashlib
import hmac
import logging

import httpx

from code_review_agent.models import PullRequestContext, ReviewComment, ReviewSummary

logger = logging.getLogger(__name__)

GITHUB_API = "https://api.github.com"


class GitHubClient:
    def __init__(self, token: str) -> None:
        self.token = token
        self._headers = {
            "Authorization": f"Bearer {token}",
            "Accept": "application/vnd.github+json",
            "X-GitHub-Api-Version": "2022-11-28",
        }

    async def get_pr_diff(self, owner: str, repo: str, number: int) -> str:
        url = f"{GITHUB_API}/repos/{owner}/{repo}/pulls/{number}"
        async with httpx.AsyncClient() as client:
            response = await client.get(
                url,
                headers={**self._headers, "Accept": "application/vnd.github.diff"},
                timeout=60.0,
            )
            response.raise_for_status()
            return response.text

    async def get_pr_context(self, owner: str, repo: str, number: int) -> PullRequestContext:
        url = f"{GITHUB_API}/repos/{owner}/{repo}/pulls/{number}"
        async with httpx.AsyncClient() as client:
            response = await client.get(url, headers=self._headers, timeout=30.0)
            response.raise_for_status()
            data = response.json()
        return PullRequestContext(
            owner=owner,
            repo=repo,
            number=number,
            title=data["title"],
            body=data.get("body") or "",
            author=data["user"]["login"],
            base_branch=data["base"]["ref"],
            head_branch=data["head"]["ref"],
            head_sha=data["head"]["sha"],
        )

    async def post_review(
        self,
        owner: str,
        repo: str,
        number: int,
        summary: ReviewSummary,
        commit_id: str,
    ) -> dict:
        event = _verdict_to_event(summary.verdict)
        body = _format_review_body(summary)
        comments = [_comment_to_github(c) for c in summary.comments if c.line]

        payload: dict = {
            "commit_id": commit_id,
            "body": body,
            "event": event,
        }
        if comments:
            payload["comments"] = comments

        url = f"{GITHUB_API}/repos/{owner}/{repo}/pulls/{number}/reviews"
        async with httpx.AsyncClient() as client:
            response = await client.post(
                url, headers=self._headers, json=payload, timeout=30.0
            )
            response.raise_for_status()
            return response.json()


def verify_webhook_signature(payload: bytes, signature: str, secret: str) -> bool:
    if not secret or not signature:
        return False
    expected = "sha256=" + hmac.new(
        secret.encode(), payload, hashlib.sha256
    ).hexdigest()
    return hmac.compare_digest(expected, signature)


def parse_webhook_payload(payload: dict) -> PullRequestContext | None:
    if payload.get("pull_request") is None:
        return None
    repo = payload["repository"]["full_name"].split("/", 1)
    pr = payload["pull_request"]
    return PullRequestContext(
        owner=repo[0],
        repo=repo[1],
        number=pr["number"],
        title=pr["title"],
        body=pr.get("body") or "",
        author=pr["user"]["login"],
        base_branch=pr["base"]["ref"],
        head_branch=pr["head"]["ref"],
        head_sha=pr["head"]["sha"],
    )


def _verdict_to_event(verdict: str) -> str:
    mapping = {
        "approve": "APPROVE",
        "comment": "COMMENT",
        "request_changes": "REQUEST_CHANGES",
    }
    return mapping.get(verdict, "COMMENT")


def _format_review_body(summary: ReviewSummary) -> str:
    lines = [
        f"## Code Review Agent — {summary.verdict.replace('_', ' ').title()}",
        "",
        summary.summary,
        "",
    ]
    if summary.strengths:
        lines.append("### Strengths")
        lines.extend(f"- {s}" for s in summary.strengths)
        lines.append("")
    if summary.risks:
        lines.append("### Risks")
        lines.extend(f"- {r}" for r in summary.risks)
        lines.append("")
    if summary.comments:
        lines.append(f"### Findings ({len(summary.comments)})")
        for c in summary.comments:
            loc = f"`{c.file}`" + (f":{c.line}" if c.line else "")
            lines.append(
                f"- **[{c.severity.value}]** {loc} — {c.title}: {c.body}"
            )
    lines.append("")
    lines.append(
        f"_Generated by Code Review Agent ({summary.agent_steps} steps, "
        f"tools: {', '.join(summary.tools_used) or 'none'})_"
    )
    return "\n".join(lines)


def _comment_to_github(comment: ReviewComment) -> dict:
    return {
        "path": comment.file,
        "line": comment.line,
        "body": (
            f"**[{comment.severity.value}/{comment.category.value}] {comment.title}**\n\n"
            f"{comment.body}"
            + (f"\n\n> Suggestion: {comment.suggestion}" if comment.suggestion else "")
        ),
    }
